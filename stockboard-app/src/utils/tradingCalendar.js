// A股交易日历(周末 + 法定节假日休市), 供 getLatestTradingDay 等"最近交易日回退"使用。
// 数据源: 上交所《关于2026年部分节假日休市安排的通知》(2025-12-22 发布)
// https://www.sse.com.cn/disclosure/dealinstruc/closed/
// ⚠️ 只收录 2026 年; 跨年后需用新一年的交易所通知更新 HOLIDAYS 与 COVERAGE。
//    覆盖期外自动退回"周一~周五"近似(与 2026-09 前的旧行为一致), 不猜测。

// 2026 年落在周一~周五的休市日(周末休市由星期判断覆盖, 不在此列)
const HOLIDAYS_2026 = new Set([
  '2026-01-01', '2026-01-02',                    // 元旦(1/1四-1/3六, 1/5开市)
  '2026-02-16', '2026-02-17', '2026-02-18', '2026-02-19', '2026-02-20', '2026-02-23', // 春节(2/15日-2/23一, 2/24开市)
  '2026-04-06',                                  // 清明(4/4六-4/6一, 4/7开市)
  '2026-05-01', '2026-05-04', '2026-05-05',      // 劳动节(5/1五-5/5二, 5/6开市)
  '2026-06-19',                                  // 端午(6/19五-6/21日, 6/22开市)
  '2026-09-25',                                  // 中秋(9/25五-9/27日, 9/28开市)
  '2026-10-01', '2026-10-02', '2026-10-05', '2026-10-06', '2026-10-07', // 国庆(10/1四-10/7三, 10/8开市)
])
const COVERAGE_YEAR = 2026

const HOLIDAYS = { 2026: HOLIDAYS_2026 }

/** 'YYYY-MM-DD' → 是否交易日(周末+已收录年份的法定节假日休市; 未收录年份只按周末近似) */
export function isTradingDay(dateStr) {
  const d = new Date(`${dateStr}T00:00:00`)
  const wd = d.getDay()
  if (wd === 0 || wd === 6) return false
  const y = d.getFullYear()
  const h = HOLIDAYS[y]
  return h ? !h.has(dateStr) : true
}
export { COVERAGE_YEAR }
