// 2027 年落在周一~周五的休市日(国务院通知 2026-11-05 发布)。
// 注: 调休上班的周末(1/31、2/14、5/8、9/26、10/9)股市照常休市——股市无周末补班开市, 由星期判断覆盖。
const HOLIDAYS_2027 = new Set([
  '2027-01-01',                                  // 元旦(1/1五-1/3日, 1/4开市)
  '2027-02-05', '2027-02-08', '2027-02-09', '2027-02-10', '2027-02-11', '2027-02-12', // 春节(2/5五-2/13六; 2/14调休上班周日股市仍休, 2/15一开市)
  '2027-04-05',                                  // 清明(4/3六-4/5一, 4/6开市)
  '2027-05-03', '2027-05-04', '2027-05-05',      // 劳动节(5/1六-5/5三, 5/6开市)
  '2027-06-09',                                  // 端午(6/9三, 6/10开市)
  '2027-09-15',                                  // 中秋(9/15三, 9/16开市)
  '2027-10-01', '2027-10-04', '2027-10-05', '2027-10-06', '2027-10-07', // 国庆(10/1五-10/7四, 10/8开市)
])
const COVERAGE_YEAR = 2027

const HOLIDAYS = { 2026: HOLIDAYS_2026, 2027: HOLIDAYS_2027 }

/** 'YYYY-MM-DD' → 是否交易日(周末+已收录年份的法定节假日休市; 未收录年份只按周末近似) */
export function isTradingDay(dateStr) {
  const d = new Date(`${dateStr}T00:00:00`)
  const wd = d.getDay()
  if (wd === 0 || wd === 6) return false
  const y = d.getFullYear()
  const h = HOLIDAYS[y]
  return h ? !h.has(dateStr) : true
}
export { COVERAGE_YEAR }
